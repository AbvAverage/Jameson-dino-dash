// Pulls the game's own art code out of public/play/index.html so the landing page
// draws the exact same Rex, Jameson, worlds and pickups as the game.
// The game file is only read, never changed.
//
//   node scripts/build-landing-art.mjs
//
// Writes:
//   public/assets/dd-art.js          REXART, JAM, SFX, JUNGLE, SKYART, ZONES, OBSART, PICKUPS, SHOP
//   public/assets/jameson-head.png   Jameson's head art (as used in the game)
//   public/assets/jungle-far.webp    the painted jungle backdrop
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const gamePath = path.join(root, 'public/play/index.html');
const outDir = path.join(root, 'public/assets');
const html = fs.readFileSync(gamePath, 'utf8');

function fail(msg) { console.error('build-landing-art: ' + msg); process.exit(1); }

// ---- images -------------------------------------------------------------
const headM = html.match(/head\.src = '(data:image\/png;base64,[A-Za-z0-9+/=]+)'/);
const farM = html.match(/JUNGLE\.setFar\('(data:image\/webp;base64,[A-Za-z0-9+/=]+)'\)/);
if (!headM || !farM) fail('could not find the head or jungle images in the game');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'jameson-head.png'), Buffer.from(headM[1].split(',')[1], 'base64'));
fs.writeFileSync(path.join(outDir, 'jungle-far.webp'), Buffer.from(farM[1].split(',')[1], 'base64'));

// ---- whole modules ------------------------------------------------------
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);
function moduleFor(name) {
  const s = scripts.find(x => new RegExp('\\nvar ' + name + ' = \\(function').test('\n' + x));
  if (!s) fail('module ' + name + ' not found');
  return s.replace(/JUNGLE\.setFar\('data:[^']+'\);/, "JUNGLE.setFar(DD_ASSET('jungle-far.webp'));").trim();
}

// ---- single functions from inside the game loop ---------------------------
const main = scripts[scripts.length - 1];
function fn(name) {
  const start = main.indexOf('  function ' + name + '(');
  if (start < 0) fail('function ' + name + ' not found');
  let i = main.indexOf('{', start), depth = 0;
  for (; i < main.length; i++) {
    if (main[i] === '{') depth++;
    else if (main[i] === '}' && --depth === 0) break;
  }
  return main.slice(start, i + 1);
}
function varLine(name) {
  const m = main.match(new RegExp('  var ' + name + ' = [\\s\\S]*?;\\n'));
  if (!m) fail('var ' + name + ' not found');
  return m[0];
}

const pickups = `
// Pickups, toy blocks and shop previews, copied from the game loop.
var PICKUPS = (function () {
  var ctx = null, t = 0, head = null, current = 'jameson';
  function wal() { return { outfit: 'truck' }; }
${fn('rr')}
${fn('glow')}
${fn('bubble')}
${fn('drawBlock')}
${fn('drawDino')}
${fn('drawTruck')}
${fn('drawPower')}
${fn('drawShot')}
${fn('previewItem')}
${varLine('blockColors')}${varLine('letters')}
  function use(c, time) { ctx = c; t = time || 0; }
  return {
    use: use,
    setHead: function (h) { head = h; },
    block: drawBlock, dino: drawDino, truck: drawTruck, power: drawPower, shot: drawShot,
    preview: previewItem, blockColors: blockColors, letters: letters
  };
})();
`;

const items = main.match(/  var ITEMS = (\[[\s\S]*?\]);/);
if (!items) fail('shop ITEMS not found');
const consts = ['POWER_TIME', 'PORTAL_EVERY', 'REX_COOL', 'BONUS_TIME'].map(k => {
  const m = main.match(new RegExp('\\b' + k + ' = (\\d+)'));
  if (!m) fail(k + ' not found');
  return k + ': ' + m[1];
}).join(', ');
const zones = main.match(/ZONE_NAMES = (\{[^}]*\})/);
if (!zones) fail('zone names not found');

const header = `/* Generated by scripts/build-landing-art.mjs from public/play/index.html. Do not edit by hand. */
var DD_ASSET = function (f) { return (window.DD_ASSET_BASE || '/assets/') + f; };
`;
const shop = `
var SHOP = { items: ${items[1]}, rules: { ${consts} }, zoneNames: ${zones[1]} };
`;
const out = header + ['REXART', 'JAM', 'SFX', 'JUNGLE', 'SKYART', 'ZONES', 'OBSART'].map(moduleFor).join('\n\n') + '\n' + pickups + shop;
fs.writeFileSync(path.join(outDir, 'dd-art.js'), out);
console.log('wrote public/assets/dd-art.js (' + (out.length / 1024).toFixed(1) + ' KB) + head + jungle backdrop');
